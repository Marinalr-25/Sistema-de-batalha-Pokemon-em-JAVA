public class Treinador {

  private String nome;
  private string pokedex;

  public Treinador(String nome, string pokedex){
    this.nome = nome;
    this.pokedex = pokedex;
  }

  public void getnome(){
    return nome;
  }
  public void setnome(String nome){
    this.nome = nome;
  }

  public void getnome(){
    return pokedex;
  }
  public void setnome(string pokedex){
    this.pokedex = pokedex;
  }
  
}
