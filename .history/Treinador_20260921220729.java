public class Treinador {

  private String nome1;
  private string pokedex;

  public Treinador(String nome, string pokedex){
    this.nome1 = nome;
    this.pokedex = pokedex;
  }

  public void getnome(){
    return nome1;
  }
  public void setnome(String nome){
    this.nome1 = nome;
  }

  public void getnome(){
    return pokedex;
  }
  public void setnome(string pokedex){
    this.pokedex = pokedex;
  }
  
}
